#!/usr/bin/env python3
"""Check maintained docs and render a task view from the existing task board."""
from pathlib import Path
import argparse
import json
import re
from urllib.parse import unquote, urlsplit
ROOT=Path(__file__).resolve().parents[1]
STATES={'not_started':'待开始','in_progress':'进行中','blocked':'阻塞','completed':'完成','cancelled':'取消'}

def render(board):
    lines=['# TODO｜工程任务看板','','<!-- Generated by tools/docs_check.py --write; edit handoff/task-board.json. -->',
           '唯一状态源为 [task-board.json](handoff/task-board.json)，详细验收见 [任务簿](handoff/EXECUTION_BACKLOG.md)。本页由工具生成，不手动维护第二份状态。',
           '', '| ID | 优先级 | 任务 | 状态 | 前置 | 需相机 |', '|---|---|---|---|---|---|']
    for t in board['tasks']:
        lines.append('| '+ ' | '.join([t['id'],t['priority'],t['title'],STATES.get(t['status'],'无效'),', '.join(t['depends_on']) or '—','是' if t['device_required'] else '否'])+' |')
    lines+=['','## 当前阻断与边界','']
    for t in board['tasks']:
        if t['status'] in ('blocked','in_progress') and t.get('note'):lines.append('- **'+t['id']+'**：'+t['note'])
    lines+=['','更新命令：`python3 tools/docs_check.py --write`；统一检查会拒绝过期看板。',
            '完成表示该任务范围已交付；主机任务完成不表示设备认证。证据引用可能是本地保留日志，远端不自动具备这些证据。','']
    return '\n'.join(lines)

def validate(root):
    errors=[]
    try:
        registry=json.loads((root/'config/documentation.json').read_text())
        board=json.loads((root/'handoff/task-board.json').read_text())
        tasks=board['tasks']; ids={t['id'] for t in tasks}
        if len(ids)!=len(tasks):errors.append('duplicate task IDs')
        graph={t['id']:t['depends_on'] for t in tasks}
        for t in tasks:
            if t['status'] not in STATES:errors.append('invalid task state: '+t['id'])
            if set(t['depends_on'])-ids:errors.append('unknown task dependency: '+t['id'])
            if t['status']=='completed' and not t.get('evidence'):errors.append('completed task needs evidence references: '+t['id'])
        active=set();done=set()
        def visit(key):
            if key in active:errors.append('task dependency cycle: '+key);return
            if key in done:return
            active.add(key)
            for dep in graph.get(key,[]):
                if dep in graph:visit(dep)
            active.remove(key);done.add(key)
        for key in graph:visit(key)
        if not (root/'TODO.md').is_file() or (root/'TODO.md').read_text()!=render(board):errors.append('TODO.md stale; run python3 tools/docs_check.py --write')
        for entry in registry['documents']:
            rel=entry['path'];path=root/rel
            if not entry.get('owner_role') or not entry.get('update_when'):errors.append('missing document maintenance owner/trigger: '+rel)
            if not path.is_file() or not path.stat().st_size:errors.append('missing document: '+rel);continue
            text=re.sub(r'```.*?```','',path.read_text(),flags=re.S)
            for target in re.findall(r'\[[^\]]*\]\(([^)]+)\)',text):
                target=target.strip('<>');uri=urlsplit(target)
                if uri.scheme or target.startswith('#'):continue
                dest=(path.parent/unquote(uri.path)).resolve()
                if not dest.is_relative_to(root.resolve()) or not dest.exists():errors.append(rel+': broken local link '+target)
    except (OSError,ValueError,KeyError,TypeError) as exc:errors.append('documentation contract: '+str(exc))
    return errors

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--write',action='store_true');args=parser.parse_args()
    if args.write:(ROOT/'TODO.md').write_text(render(json.loads((ROOT/'handoff/task-board.json').read_text())))
    errors=validate(ROOT)
    for error in errors:print('FAIL',error)
    print('FAIL documentation contracts' if errors else 'PASS documentation contracts and task view')
    return bool(errors)
if __name__=='__main__':raise SystemExit(main())
